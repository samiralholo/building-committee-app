// Generates src/environments/environment.ts from environment variables
// (Vercel / GitHub) or from a local .env file. Runs before `start` and `build`.
// The Supabase anon key is designed to be public: security is enforced by RLS.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function loadDotEnv(file) {
  const vars = {};
  if (!existsSync(file)) return vars;
  for (const raw of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

const fileVars = { ...loadDotEnv(resolve(root, '.env')), ...loadDotEnv(resolve(root, '.env.local')) };
const get = (key, fallback = '') => process.env[key] ?? fileVars[key] ?? fallback;

const env = {
  supabaseUrl: get('SUPABASE_URL').replace(/\/+$/, ''),
  supabaseAnonKey: get('SUPABASE_ANON_KEY'),
  defaultBuildingSlug: get('DEFAULT_BUILDING_SLUG'),
  enablePublicSignup: get('ENABLE_PUBLIC_SIGNUP', 'false').toLowerCase() === 'true',
};

const out = resolve(root, 'src/environments/environment.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/set-env.mjs — do not edit, do not commit.\n` +
    `import type { AppEnvironment } from './environment.model';\n\n` +
    `export const environment: AppEnvironment = ${JSON.stringify(env, null, 2)};\n`,
);

if (!env.supabaseUrl || !env.supabaseAnonKey) {
  console.warn('⚠️  SUPABASE_URL / SUPABASE_ANON_KEY are not set. The app will build but show a setup notice.');
} else {
  console.log(`✓ environment.ts generated for ${env.supabaseUrl}`);
}
